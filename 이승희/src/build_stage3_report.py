def parse_raw_data_sources():
    """data/RAW_DATA_SOURCES.md를 코드로 직접 파싱하여 안건 5 표의 파일 번호와 기간 추출"""
    doc_p = DATA_DIR / "RAW_DATA_SOURCES.md"
    text = doc_p.read_text(encoding="utf-8")
    
    # 2.2 서울시 상권분석서비스 (상권 단위) 표 파싱
    m_periods = {}
    for line in text.splitlines():
        if line.startswith("| `OA-") or line.startswith("| `추정매출") or line.startswith("| `점포"):
            parts = [p.strip() for p in line.split("|")[1:-1]]
            if len(parts) >= 3:
                fname = parts[0].replace("`", "")
                period = parts[2]
                if "OA-15560" in fname: m_periods["OA-15560"] = period
                elif "OA-15568" in fname: m_periods["OA-15568"] = period
                elif "OA-15569" in fname: m_periods["OA-15569"] = period
                elif "OA-15572" in fname: m_periods["OA-15572"] = period
                elif "OA-15576" in fname: m_periods["OA-15576"] = period
                elif "OA-15577" in fname: m_periods["OA-15577"] = period
                elif "OA-15580" in fname: m_periods["OA-15580"] = period
                elif "OA-15584" in fname: m_periods["OA-15584"] = period
    
    # zip 행 파싱
    sales_zip_years = "2023·2024"
    store_zip_years = "2023·2024"
    for line in text.splitlines():
        if "추정매출_상권_2023.zip" in line:
            parts = [p.strip() for p in line.split("|")[1:-1]]
            if len(parts) >= 3:
                years = [y.strip() for y in parts[2].replace("전체", "").split(",") if y.strip()]
                if years:
                    sales_zip_years = "·".join(years)
        elif "점포_상권_2023.zip" in line:
            parts = [p.strip() for p in line.split("|")[1:-1]]
            if len(parts) >= 3:
                years = [y.strip() for y in parts[2].replace("전체", "").split(",") if y.strip()]
                if years:
                    store_zip_years = "·".join(years)

    sales_q_p = m_periods.get("OA-15572", "2025Q1 ~ 2026Q2")
    store_q_p = m_periods.get("OA-15577", "2025Q1 ~ 2026Q2")
    m_periods["OA-15572"] = f"{sales_q_p}, 그리고 {sales_zip_years} zip 기록"
    m_periods["OA-15577"] = f"{store_q_p}, 그리고 {store_zip_years} zip 기록"
    m_periods["OA-22166"] = "문서에 기간 기재 없음"
    return m_periods


def get_actual_raw_storage_periods():
    """저장소 data/raw 내 실제 파일의 보유 기간을 코드로 직접 계산"""
    trade_dir = DATA_DIR / "raw" / "상권"
    storage_periods = {}
    
    # 1. OA-15560 영역
    f_area = trade_dir / "OA-15560_영역_상권.csv"
    if f_area.exists():
        try:
            area_cnt = len(pd.read_csv(f_area, encoding="utf-8-sig"))
        except Exception:
            area_cnt = len(pd.read_csv(f_area, encoding="cp949"))
        storage_periods["OA-15560"] = f"1개 파일, {area_cnt:,}개 상권 영역"
    
    # 2. 상권 분기 파일 7종 (break 없이 파일 전체를 읽어 분기 집계)
    trade_files = {
        "OA-15568": trade_dir / "OA-15568_길단위인구_상권.csv",
        "OA-15569": trade_dir / "OA-15569_직장인구_상권.csv",
        "OA-15572": trade_dir / "OA-15572_추정매출_상권.csv",
        "OA-15576": trade_dir / "OA-15576_상권변화지표_상권.csv",
        "OA-15577": trade_dir / "OA-15577_점포_상권.csv",
        "OA-15580": trade_dir / "OA-15580_집객시설_상권.csv",
        "OA-15584": trade_dir / "OA-15584_상주인구_상권.csv"
    }
    for code, fp in trade_files.items():
        if fp.exists():
            chunk_qs = set()
            try:
                for chunk in pd.read_csv(fp, usecols=["기준_년분기_코드"], chunksize=50000):
                    chunk_qs.update(chunk["기준_년분기_코드"].unique())
            except Exception:
                for chunk in pd.read_csv(fp, encoding="cp949", usecols=["기준_년분기_코드"], chunksize=50000):
                    chunk_qs.update(chunk["기준_년분기_코드"].unique())
            qs = sorted(list(chunk_qs))
            q_strs = [f"{str(q)[:4]}Q{str(q)[4:]}" for q in qs]
            storage_periods[code] = f"1개 파일 ({', '.join(q_strs)})"
                
    # 3. OA-22166 소비 파일
    f_cons = DATA_DIR / "raw" / "OA-22166_소비_행정동.csv"
    if f_cons.exists():
        qs_cons = set()
        try:
            for chunk in pd.read_csv(f_cons, usecols=["기준_년분기_코드"], chunksize=50000):
                qs_cons.update(chunk["기준_년분기_코드"].unique())
        except Exception:
            for chunk in pd.read_csv(f_cons, encoding="cp949", usecols=["기준_년분기_코드"], chunksize=50000):
                qs_cons.update(chunk["기준_년분기_코드"].unique())
        qs = sorted(list(qs_cons))
        q_strs = [f"{str(q)[:4]}Q{str(q)[4:]}" for q in qs]
        storage_periods["OA-22166"] = f"1개 파일 ({', '.join(q_strs)})"
            
    return storage_periods


